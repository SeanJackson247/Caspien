#!/usr/bin/env python3
"""Writes tests/codegen_leaf_string_test.caspien: the check lines come from the Java originals (Gen2 reflection harness, see header of the test)."""
import sys
lines = open(sys.argv[1]).read()
head = '''// Differential test of the converted string-valued leaf methods of codegenCaspien against the Java originals (check lines generated by gen_codegen_leaf_string_test.py from the Java classes).
import "../stdlib/libc.caspien"
import "../stdlib/gt/*"
import "../Codegen/src/main/java/caspien/codegen/x86backend/X86Backend.caspien"

func check(name: static imut string, ok: imut bool) void{
	unsafe extern{
		if ok{ printf("PASS %s\\n", name) }
		else{ printf("FAIL %s\\n", name) }
	}
}

func t_pred(name: static imut string, tok: static imut string) mut bool{
	?catch(e){ return false }
	let s = mut ? new String(tok)
	let r = mut false
	match Some(s){
		if String.literalsEqual(name, "rfIsTemp"){ r = X86Core.rfIsTemp(s) }
		elseif String.literalsEqual(name, "rfIsVar"){ r = X86Core.rfIsVar(s) }
		elseif String.literalsEqual(name, "rfIsImm"){ r = X86Core.rfIsImm(s) }
		elseif String.literalsEqual(name, "rfIsSlot"){ r = X86Core.rfIsSlot(s) }
		elseif String.literalsEqual(name, "rfIsGlobal"){ r = X86Core.rfIsGlobal(s) }
		elseif String.literalsEqual(name, "rfIsXvar"){ r = X86Core.rfIsXvar(s) }
		elseif String.literalsEqual(name, "isCharLiteral"){ r = X86Core.isCharLiteral(s) }
		else{ r = X86Core.isInteger(s) }
	}
	return r
}

func t_num(name: static imut string, tok: static imut string) owns mut String{
	?catch(e){ return null }
	let s = mut ? new String(tok)
	let:<mut s64> v = mut 0
	match Some(s){
		if String.literalsEqual(name, "rfImm"){
			v = try X86Core.rfImm(s) catch(err){ return null }
		} else{
			v = try X86Core.rfSlot(s) catch(err){ return null }
		}
	}
	let out = mut ? String.fromS64(v)
	return out
}

func t_lit(name: static imut string, op: static imut string) static imut string{
	?catch(e){ return "EX" }
	let s = mut ? new String(op)
	match Some(s){
		let r = try X86Core.rfFalseJump(s) catch(err){ return "EX" }
		return r
	}
	return "EX"
}

func t_mirror(cc: static imut string) static imut string{
	return X86Core.rfMirrorJump(cc)
}

func t_suffix(cc: static imut string) static imut string{
	let r = try X86Core.rfTrueSuffix(cc) catch(err){ return "EX" }
	return r
}

'''
print(head, end="")
print('''func checkS(name: static imut string, f: static imut string, tok: static imut string, want: static imut string) void{
	let got = mut t_num(f, tok)
	let ok = mut String.literalsEqual(want, "EX")
	match Some(got){
		ok = got.equals(got, want)
	}
	check(name, ok)
}

func t_sse(size: mut s32) static imut string{
	?catch(e){ return "EX" }
	let b = mut ? new X86Backend(CodegenTarget.LINUX_X64)
	? b.wire(b)
	match Some(b.calls){ return b.calls.sseSuffix(b.calls, size) }
	return "EX"
}

func t_mov(size: mut s32) static imut string{
	?catch(e){ return "EX" }
	let b = mut ? new X86Backend(CodegenTarget.LINUX_X64)
	? b.wire(b)
	match Some(b.emit){ return b.emit.movSuffix(b.emit, size) }
	return "EX"
}

func t_fsfx(size: mut s32) static imut string{ return X86Generator.fsfx(size) }
func t_wsfx(size: mut s32) static imut string{ return X86Generator.widthSfx(size) }
func t_fmov(size: mut s32) static imut string{ return X86Generator.fmov(size) }
''')
body = lines.split("\n")
body = [l for l in body if l.strip()]
n = 0
parts = []
for i in range(0, len(body), 120):
    parts.append(body[i:i+120])
for k, ps in enumerate(parts):
    print("func part%d() void{" % k)
    print("\n".join(ps))
    print("}\n")
print("func main() void{")
for k in range(len(parts)):
    print("\tpart%d()" % k)
print("}")
