#!/usr/bin/env python3
"""usage: gen_codegen_pipeline_test.py > tests/codegen_pipeline_test.caspien
End-to-end differential test of the Codegen port WITH the real BytecodeParser port: the LOB text of 18 cached programs (chosen like the generate test) goes
through Codegen.generate(lobText, origin, configText) on both sides (Java original and Caspien port), 4 configs each, plus line-ending variants."""
import os, sys, subprocess, tempfile, shutil
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_codegen_generate_test as GG
REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GG.ROOT = REPO
REF = os.path.join(REPO, "ReferenceImplementation")
CFGS = [("target linux\n", "linux"), ("target windows_gnu\n", "win"), ("target linux\nbmi2 on\navx on\n", "linux+"), ("target windows_gnu\nbmi2 on\navx on\n", "win+")]

def esc(s): return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t").replace("$", "\\$")

def main():
    chosen, _ = GG.pick(GG.corpus())
    progs = []
    for i, (f, t) in enumerate(chosen):
        progs.append(("p%d" % i, t))
    progs.append(("crlf", chosen[0][1].replace("\n", "\r\n")))
    progs.append(("nofinal", chosen[1][1].rstrip("\n")))
    progs.append(("blank", "\n" + chosen[2][1].replace("\n", "\n\n", 3)))
    progs = progs[:int(os.environ.get("PIPE_MAX", "99"))]   # PIPE_MAX: fewer programs (quick aggressive-config runs)
    tmp = tempfile.mkdtemp(prefix="cgp", dir="/tmp/bpt")
    os.makedirs(tmp + "/lob")
    for i, (n, t) in enumerate(progs):
        open("%s/lob/%d.lob" % (tmp, i), "w", newline="").write(t)
    J = '''import caspien.codegen.*; import java.nio.file.*;
public class GenPipe {
  static String q(String s) { return s.replace("\\\\", "\\\\\\\\").replace("\\"", "\\\\\\"").replace("\\n", "\\\\n").replace("\\r", "\\\\r").replace("\\t", "\\\\t").replace("$", "\\\\$"); }
  public static void main(String[] a) throws Exception {
    String[] cfg = {%s};
    String[] names = {%s};
    for (int i = 0; i < %d; i++) {
      String lob = new String(Files.readAllBytes(Paths.get(a[0] + "/lob/" + i + ".lob")), "ISO-8859-1");
      for (int c = 0; c < cfg.length; c++) {
        CodegenResult r = Codegen.generate(lob, "x.lob", cfg[c]);
        System.out.println("\\tc_pipe(\\"" + names[i] + " " + c + "\\", \\"" + q(lob) + "\\", \\"" + q(cfg[c]) + "\\", \\"" + q(r.failed ? "@@FAILED@@" : r.asm) + "\\")");
      }
    }
  }
}
''' % (", ".join('"%s"' % esc(c[0]) for c in CFGS), ", ".join('"%s"' % n for n, _ in progs), len(progs))
    open(tmp + "/GenPipe.java", "w").write(J)
    cls = tmp + "/cls"; os.makedirs(cls)
    cp = REF + "/Codegen/out"; env = dict(os.environ, JAVA_TOOL_OPTIONS="")
    subprocess.check_call(["javac", "-cp", cp, "-d", cls, tmp + "/GenPipe.java"], env=env)
    lines = [l for l in subprocess.check_output(["java", "-cp", cp + ":" + cls, "GenPipe", tmp], env=env).decode("latin-1").split("\n") if l.strip()]
    shutil.rmtree(tmp, ignore_errors=True)
    T = '''// End-to-end test of Codegen.generate (real BytecodeParser port) against the Java original (generated by gen_codegen_pipeline_test.py).
import "stdlib/libc.caspien"
import "stdlib/gt/*"
import "stdlib/string.caspien"
import "../Codegen/src/main/java/caspien/codegen/Codegen.caspien"

func check(name: static imut string, ok: imut bool) void{
	unsafe extern{
		if ok{ printf("PASS %%s\\n", name) }
		else{ printf("FAIL %%s\\n", name) }
	}
}

func c_pipe(label: static imut string, lob: static imut string, cfg: static imut string, want: static imut string) void{
	?catch(ex){
		check(label, false)
		return
	}
	let l = mut ? new String(lob)
	let o = mut ? new String("x.lob")
	let c = mut ? new String(cfg)
	let r = mut Codegen.generate(l, o, c)
	let ok = mut false
	match Some(r){
		if r.failed{
			ok = String.literalsEqual(want, "@@FAILED@@")
		} else{
			match Some(r.asm){ ok = r.asm.equals(r.asm, want) }
		}
	}
	check(label, ok)
}
'''
    parts = [lines[i:i + 20] for i in range(0, len(lines), 20)]
    for k, ps_ in enumerate(parts): T += "\nfunc part%d() void{\n%s\n}\n" % (k, "\n".join(ps_))
    T += "\nfunc main() void{\n" + "".join("\tpart%d()\n" % k for k in range(len(parts))) + "}\n"
    sys.stdout.write(T)
main()
