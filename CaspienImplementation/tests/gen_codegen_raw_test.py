#!/usr/bin/env python3
"""usage: gen_codegen_raw_test.py lines.txt > tests/codegen_raw_test.caspien (lines: c_raw calls printed by a Java harness over X86Emit.raw/trackStackDelta/strideKeyAfter)."""
import sys, re
rows = [l.rstrip("\n") for l in open(sys.argv[1]).read().split("\n") if l.strip()]
HEAD = '''// Differential test of the converted raw / trackStackDelta / strideKeyAfter against the Java originals (check lines generated by gen_codegen_raw_test.py).
import "../stdlib/libc.caspien"
import "../stdlib/gt/*"
import "../Codegen/src/main/java/caspien/codegen/x86backend/X86Backend.caspien"

func check(name: static imut string, ok: imut bool) void{
	unsafe extern{
		if ok{ printf("PASS %s\\n", name) }
		else{ printf("FAIL %s\\n", name) }
	}
}

func nb(win: imut bool) owns mut X86Backend{
	?catch(e){ return null }
	if win{
		let w = mut ? new X86Backend(CodegenTarget.WINDOWS_GNU_X64)
		? w.wire(w)
		return w
	}
	let b = mut ? new X86Backend(CodegenTarget.LINUX_X64)
	? b.wire(b)
	return b
}

func chk(name: static imut string, got: ref imut String, want: static imut string) void{
	let ok = mut String.literalsEqual(want, "EX")
	match Some(got){
		ok = got.equals(got, want)
	}
	check(name, ok)
}

func t_raw(text: static imut string, st: mut s32, sus: mut s32, sink: imut bool, buf: imut bool, idx: static imut string) owns mut String{
	?catch(e){ return null }
	let b = mut nb(false)
	let tx = mut ? new String(text)
	let ix = mut ? new String(idx)
	if st >= 0{
		match Some(b){ match Some(b.core){ ? b.core.argTrackDeltaStack.pushBack(b.core.argTrackDeltaStack, wrap:<s64>(st)) } }
	}
	match Some(b){ match Some(b.core){ b.core.argTrackSuspendDepth = sus } }
	if buf{
		let bf = mut ? new String()
		match Some(b){ match Some(b.core){ ? b.core.callBufferStack.add(b.core.callBufferStack, bf) } }
	}
	if sink{
		match Some(b){ match Some(b.core){ b.core.strideKeyIdx = ix } }
		if buf{
			match Some(b){ match Some(b.core){ b.core.strideKeySink = b.core.callBufferStack.peek(b.core.callBufferStack) } }
		} else{
			match Some(b){ match Some(b.core){ b.core.strideKeySink = ref b.core.out } }
		}
	}
	match Some(b){ match Some(b.emit){ ? b.emit.raw_(b.emit, tx) } }
	let out = mut ? new String("top=")
	let empty = mut false
	let:<mut s64> topv = mut 0
	match Some(b){ match Some(b.core){
		empty = len(b.core.argTrackDeltaStack.backing) == 0
		let n = mut len(b.core.argTrackDeltaStack.backing)
		if empty == false{
			let last = mut (n - 1)
			match last in b.core.argTrackDeltaStack.backing{ topv = b.core.argTrackDeltaStack.backing[last] }
		}
	} }
	if empty{
		? out.append(out, "empty")
	} else{
		? out.appendS64(out, topv)
	}
	let sinkNull = mut false
	let outText = mut ? new String()
	let bufText = mut ? new String()
	match Some(b){ match Some(b.core){
		sinkNull = b.core.strideKeySink == null
		outText = ? b.core.out.substring(b.core.out, 0)
	} }
	if buf{
		match Some(b){ match Some(b.core){
			let top = b.core.callBufferStack.peek(b.core.callBufferStack)
			match Some(top){ bufText = ? top.substring(top, 0) }
		} }
	}
	if sinkNull{
		? out.append(out, ";sink=null")
	} else{
		? out.append(out, ";sink=set")
	}
	? out.append(out, ";out=")
	? out.append(out, outText)
	? out.append(out, ";buf=")
	? out.append(out, bufText)
	return out
}

func c_raw(name: static imut string, text: static imut string, st: mut s32, sus: mut s32, sink: imut bool, buf: imut bool, idx: static imut string, want: static imut string) void{
	let r = mut t_raw(text, st, sus, sink, buf, idx)
	chk(name, r, want)
}
'''
print(HEAD)
parts = [rows[i:i + 100] for i in range(0, len(rows), 100)]
for k, ps in enumerate(parts):
    print("func part%d() void{" % k)
    print("\n".join(ps))
    print("}\n")
print("func main() void{")
for k in range(len(parts)):
    print("\tpart%d()" % k)
print("}")
