#!/usr/bin/env python3
"""usage: gen_codegen_generate_test.py > tests/codegen_generate_test.caspien
Whole-program differential test of the converted X86Backend.generate: LOB files from the stage cache (.cache/stages/s3/*/out, chosen greedily so every
mnemonic form is covered) are parsed by the real Java BytecodeParser; the token lists go into the Caspien test, which builds the same statements, runs
X86Backend.generate and compares the assembly text with what the Java original produced (both targets, a few avx/bmi2 settings)."""
import shutil, sys, os, glob, subprocess, tempfile
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAXLINES, MAXFILES = 420, 18
def corpus():
    seen, files = set(), []
    for f in sorted(glob.glob(ROOT + "/.cache/stages/s3/*/out")):
        t = open(f, errors="replace").read()
        if t in seen or t.count("\n") > MAXLINES or "\t" in t: continue
        seen.add(t); files.append((f, t))
    return files
def pick(files):
    covered, chosen = set(), []
    def keys(t):
        ks = set()
        for ln in t.split("\n"):
            w = ln.split()
            if w: ks.add((w[0], len(w) if w[0].startswith("R_") or w[0] in ("PUSH", "NEW", "DOT") else 0))
        return ks
    while len(chosen) < MAXFILES:
        best = max(files, key=lambda ft: (len(keys(ft[1]) - covered), -len(ft[1])))
        gain = keys(best[1]) - covered
        if len(gain) == 0: break
        covered |= gain; chosen.append(best); files = [x for x in files if x is not best]
    return chosen, covered
def esc(s): return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
def main():
    chosen, covered = pick(corpus())
    cfgs = [("linux", False, False), ("windows", False, False), ("linux", True, True), ("windows", True, True)]
    tmp = tempfile.mkdtemp(); os.makedirs(tmp + "/lob")
    for i, (f, t) in enumerate(chosen): open("%s/lob/%d.lob" % (tmp, i), "w").write(t)
    J = '''package caspien.codegen.x86backend;
import caspien.codegen.CodegenTarget; import caspien.bytecode.*; import java.util.*; import java.nio.file.*;
public class GenGen {
  static String q(String s) { return s.replace("\\\\", "\\\\\\\\").replace("\\"", "\\\\\\"").replace("\\n", "\\\\n").replace("\\t", "\\\\t"); }
  public static void main(String[] a) throws Exception {
    for (int i = 0; i < %d; i++) {
      List<String> raw = Files.readAllLines(Paths.get(a[0] + "/lob/" + i + ".lob"));
      BytecodeProgram p = new BytecodeParser().parse(raw, "x.lob");
      List<BytecodeStatement> ls = new ArrayList<>(); for (BytecodeStatement s : p) ls.add(s);
      StringBuilder prog = new StringBuilder();
      for (BytecodeStatement s : ls) { for (int k = 0; k < s.size(); k++) { if (k > 0) prog.append('\\t'); prog.append(s.get(k).text); } prog.append('\\n'); }
      String[][] cfg = {%s};
      for (String[] c : cfg) {
        X86Backend b = new X86Backend(c[0].equals("linux") ? CodegenTarget.LINUX_X64 : CodegenTarget.WINDOWS_GNU_X64, c[2].equals("1"));
        b.avx = c[1].equals("1");
        List<BytecodeStatement> copy = new ArrayList<>(ls);
        String asm; try { asm = b.generate(copy); } catch (RuntimeException ex) { asm = "@@EXCEPTION@@"; }
        System.out.println("\\tc_gen(\\"gen " + i + " " + c[0] + " " + c[1] + c[2] + "\\", " + (c[0].equals("linux") ? 0 : 1) + ", " + (c[1].equals("1") ? "true" : "false") + ", " + (c[2].equals("1") ? "true" : "false") + ", \\"" + q(prog.toString()) + "\\", \\"" + q(asm) + "\\")");
      }
    }
  }
}
''' % (len(chosen), ", ".join('{"%s","%d","%d"}' % (t, int(av), int(bm)) for (t, av, bm) in cfgs))
    os.makedirs(tmp + "/caspien/codegen/x86backend")
    open(tmp + "/caspien/codegen/x86backend/GenGen.java", "w").write(J)
    out = tmp + "/cls"; os.makedirs(out)
    cp = ROOT + "/Codegen/out"; env = dict(os.environ, JAVA_TOOL_OPTIONS="")
    subprocess.check_call(["javac", "-cp", cp, "-d", out, tmp + "/caspien/codegen/x86backend/GenGen.java"], env=env)
    lines = [l for l in subprocess.check_output(["java", "-cp", cp + ":" + out, "caspien.codegen.x86backend.GenGen", tmp], env=env).decode().split("\n") if l.strip()]
    shutil.rmtree(tmp, ignore_errors=True)
    T = '''// Whole-program differential test of X86Backend.generate against the Java original (generated by gen_codegen_generate_test.py).
import "stdlib/libc.caspien"
import "stdlib/gt/*"
import "../Codegen/src/main/java/caspien/codegen/x86backend/X86Backend.caspien"

func check(name: static imut string, ok: imut bool) void{
	unsafe extern{
		if ok{ printf("PASS %%s\\n", name) }
		else{ printf("FAIL %%s\\n", name) }
	}
}

func buildProgram(ll: ref mut ObjectList<BytecodeStatement>, prog: static imut string) void{
	?catch(e){ return }
	let t = mut ? new String(prog)
	let:<mut u64> n = mut 0
	match Some(t){ n = t.length(t) }
	let st = mut ? new BytecodeStatement()
	let cur = mut ? new String()
	for i in 0..n{
		let c = mut ' '
		match Some(t){ c = t.charAt(t, i) }
		if c == '\\t'{
			let file = mut ? String.from("t")
			let tok = mut ? new BytecodeToken(cur, file, 1, BytecodeTokenKind.CODE)
			match Some(st){ ? st.items.add(st.items, tok) }
			cur = ? new String()
		} elseif c == '\\n'{
			let file2 = mut ? String.from("t")
			let tok2 = mut ? new BytecodeToken(cur, file2, 1, BytecodeTokenKind.CODE)
			match Some(st){ ? st.items.add(st.items, tok2) }
			cur = ? new String()
			match Some(ll){ ? ll.add(ll, st) }
			st = ? new BytecodeStatement()
		} else{
			match Some(cur){ ? cur.appendChar(cur, c) }
		}
	}
}

func c_gen(label: static imut string, tgt: mut s32, avx: mut bool, bmi2: mut bool, prog: static imut string, want: static imut string) void{
	?catch(ex){
		check(label, false)
		return
	}
	let ll = mut ? new ObjectList:<BytecodeStatement>()
	buildProgram(ll, prog)
	let b = mut ? new X86Backend(CodegenTarget.LINUX_X64, bmi2)
	if tgt == 1{
		b = ? new X86Backend(CodegenTarget.WINDOWS_GNU_X64, bmi2)
	}
	? b.wire(b)
	if avx{
		b.avx = true
	}
	let:<owns mut String> asm = mut null
	let thrown = mut false
	try{
		asm = try b.generate(b, ll) catch(e){
			thrown = true
			continue
		}
	}
	let ok = mut false
	if thrown{
		ok = String.literalsEqual(want, "@@EXCEPTION@@")
	} else{
		match Some(asm){ ok = asm.equals(asm, want) }
	}
	check(label, ok)
}
''' % ()
    parts = [lines[i:i + 20] for i in range(0, len(lines), 20)]
    for k, ps_ in enumerate(parts): T += "\nfunc part%d() void{\n%s\n}\n" % (k, "\n".join(ps_))
    T += "\nfunc main() void{\n" + "".join("\tpart%d()\n" % k for k in range(len(parts))) + "}\n"
    sys.stderr.write("%d files, %d mnemonic forms covered\n" % (len(chosen), len(covered)))
    sys.stdout.write(T)
if __name__ == "__main__":
    main()
