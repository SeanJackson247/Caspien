#!/usr/bin/env python3
"""usage: gen_codegen_csr_test.py lines.txt > tests/codegen_csr_test.caspien (lines: c_fcs calls printed by a Java harness over X86Generator.finishCalleeSaved)."""
import sys, re
rows = [l.rstrip("\n") for l in open(sys.argv[1]).read().split("\n") if l.strip()]
HEAD = '''// Differential test of the converted finishCalleeSaved against the Java original (check lines generated by gen_codegen_csr_test.py).
import "../stdlib/libc.caspien"
import "../stdlib/gt/*"
import "../Codegen/src/main/java/caspien/codegen/x86backend/X86Backend.caspien"

func check(name: static imut string, ok: imut bool) void{
	unsafe extern{
		if ok{ printf("PASS %s\\n", name) }
		else{ printf("FAIL %s\\n", name) }
	}
}

func nb(win: imut bool) owns mut X86Backend{
	?catch(e){ return null }
	if win{
		let w = mut ? new X86Backend(CodegenTarget.WINDOWS_GNU_X64)
		? w.wire(w)
		return w
	}
	let b = mut ? new X86Backend(CodegenTarget.LINUX_X64)
	? b.wire(b)
	return b
}

func chk(name: static imut string, got: ref imut String, want: static imut string) void{
	let ok = mut String.literalsEqual(want, "EX")
	match Some(got){
		ok = got.equals(got, want)
	}
	check(name, ok)
}

func fill(lines: ref mut ObjectList<BytecodeStatement>, spec: static imut string) void{
	?catch(e){ return }
	let s = mut ? new String(spec)
	let stmt = mut ? new BytecodeStatement()
	let tok = mut ? new String()
	let n = mut s.length(s)
	for i in 0..n{
		let c = mut s.charAt(s, i)
		if c == ' ' || c == ';'{
			let f = mut ? new String("f")
			let tk = mut ? new BytecodeToken(tok, f, 1, BytecodeTokenKind.CODE)
			? stmt.items.add(stmt.items, tk)
			tok = ? new String()
			if c == ';'{
				match Some(lines){ ? lines.add(lines, stmt) }
				stmt = ? new BytecodeStatement()
			}
		} else{
			? tok.appendChar(tok, c)
		}
	}
}

func t_fcs(win: imut bool, text: static imut string, fs: mut s32, allocPos: mut s32, allocBytes: mut s64, alLine: static imut string, alNull: imut bool, allocSum: mut s64, mask: mut s32) owns mut String{
	?catch(e){ return null }
	let b = mut nb(win)
	let t = mut ? new String(text)
	let al = mut ? new String(alLine)
	match Some(b){ match Some(b.core){ b.core.out = t } }
	match Some(b){ match Some(b.core){
		b.core.csrFuncStart = fs
		b.core.csrAllocPos = allocPos
		b.core.csrAllocBytes = allocBytes
		b.core.csrAllocSum = allocSum
		b.core.rfVarMask = mask
	} }
	if alNull == false{
		match Some(b){ match Some(b.core){ b.core.csrAllocLine = al } }
	}
	match Some(b){ match Some(b.gen){ ? b.gen.finishCalleeSaved(b.gen) } }
	let out = mut ? new String()
	match Some(b){ match Some(b.core){ out = ? b.core.out.substring(b.core.out, 0) } }
	? out.append(out, "|start=")
	let:<mut s32> st = mut 0
	match Some(b){ match Some(b.core){ st = b.core.csrFuncStart } }
	? out.appendS64(out, wrap:<s64>(st))
	? out.append(out, "|vs=")
	for z in 0..3{
		if z > 0{ ? out.append(out, ",") }
		let sl = mut ? new String()
		match Some(b){ match Some(b.core){
			let v = b.core.vSlots.get(b.core.vSlots, z)
			match Some(v){ sl = ? v.substring(v, 0) }
		} }
		? out.append(out, sl)
	}
	return out
}

func c_fcs(name: static imut string, win: imut bool, text: static imut string, fs: mut s32, allocPos: mut s32, allocBytes: mut s64, alLine: static imut string, alNull: imut bool, allocSum: mut s64, mask: mut s32, want: static imut string) void{
	let r = mut t_fcs(win, text, fs, allocPos, allocBytes, alLine, alNull, allocSum, mask)
	chk(name, r, want)
}
'''
print(HEAD)
parts = [rows[i:i + 100] for i in range(0, len(rows), 100)]
for k, ps in enumerate(parts):
    print("func part%d() void{" % k)
    print("\n".join(ps))
    print("}\n")
print("func main() void{")
for k in range(len(parts)):
    print("\tpart%d()" % k)
print("}")
