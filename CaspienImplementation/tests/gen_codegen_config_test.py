#!/usr/bin/env python3
"""usage: gen_codegen_config_test.py lines.txt > tests/codegen_config_test.caspien (lines: c_cfg calls printed by a Java harness over CodegenConfig.parse)."""
import sys, re
rows = [l.strip() for l in open(sys.argv[1]).read().split("\n") if l.strip()]
HEAD = '''// Differential test of the converted CodegenConfig.parse against the Java original (check lines generated by gen_codegen_config_test.py).
import "../stdlib/libc.caspien"
import "../stdlib/gt/*"
import "../Codegen/src/main/java/caspien/codegen/CodegenConfig.caspien"

func check(name: static imut string, ok: imut bool) void{
	unsafe extern{
		if ok{ printf("PASS %s\\n", name) }
		else{ printf("FAIL %s\\n", name) }
	}
}

func t_cfg(text: static imut string) owns mut String{
	?catch(e){ return null }
	let s = mut ? new String(text)
	let p = mut ? new String("p")
	let c = mut ? CodegenConfig.parse(s, p)
	let out = mut ? new String()
	if c.target == CodegenTarget.LINUX_X64{
		? out.append(out, "LINUX_X64")
	} else{
		? out.append(out, "WINDOWS_GNU_X64")
	}
	if c.bmi2{ ? out.append(out, ",true") } else{ ? out.append(out, ",false") }
	if c.avx{ ? out.append(out, ",true") } else{ ? out.append(out, ",false") }
	return out
}

func c_cfg(name: static imut string, text: static imut string, want: static imut string) void{
	let r = mut t_cfg(text)
	let ok = mut String.literalsEqual(want, "EX")
	match Some(r){
		ok = r.equals(r, want)
	}
	check(name, ok)
}
'''
print(HEAD)
parts = [rows[i:i + 100] for i in range(0, len(rows), 100)]
n = 0
for k, ps in enumerate(parts):
    print("func part%d() void{" % k)
    for l in ps:
        n += 1
        print(l.replace('"CodegenConfig.parse"', '"CodegenConfig.parse %d"' % n, 1).replace("c_cfg(", "\tc_cfg(", 1) if False else "\t" + l.replace('"CodegenConfig.parse"', '"CodegenConfig.parse %d"' % n, 1))
    print("}\n")
print("func main() void{")
for k in range(len(parts)):
    print("\tpart%d()" % k)
print("}")
