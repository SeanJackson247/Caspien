#!/usr/bin/env python3
"""usage: gen_codegen_string2_test.py lines.txt > tests/codegen_string2_test.caspien (lines: check calls printed by a Java reflection harness over the originals)."""
import sys
lines = [l.replace('(-9223372036854775807 - 1)', 't_min()') for l in open(sys.argv[1]).read().split("\n") if l.strip()]
HEAD = '''// Differential test of the converted run-time-String leaf methods of codegenCaspien against the Java originals (check lines generated by gen_codegen_string2_test.py).
import "stdlib/libc.caspien"
import "stdlib/gt/*"
import "../Codegen/src/main/java/caspien/codegen/codegenCaspien/x86backend/X86Backend.caspien"

func check(name: static imut string, ok: imut bool) void{
	unsafe extern{
		if ok{ printf("PASS %s\\n", name) }
		else{ printf("FAIL %s\\n", name) }
	}
}

// got == null means the method threw; want "EX" means the Java threw.
func chk(name: static imut string, got: ref imut String, want: static imut string) void{
	let ok = mut String.literalsEqual(want, "EX")
	match Some(got){
		ok = got.equals(got, want)
	}
	check(name, ok)
}

func chkn(name: static imut string, got: owns mut String, want: static imut string) void{
	chk(name, got, want)
}

func nb() owns mut X86Backend{
	?catch(e){ return null }
	let b = mut ? new X86Backend(CodegenTarget.LINUX_X64)
	? b.wire(b)
	return b
}

func t_x(a: static imut string) owns mut String{
	?catch(e){ return null }
	let b = mut nb()
	match Some(b){ match Some(b.gen){
		let r = mut ? b.gen.xText(b.gen, a)
		return r
	} }
	return null
}

func t_ml(a: static imut string) owns mut String{
	?catch(e){ return null }
	let b = mut nb()
	let s = mut ? new String(a)
	match Some(b){ match Some(b.gen){ match Some(s){
		let r = mut ? b.gen.mangleLabel(b.gen, s)
		return r
	} } }
	return null
}

func t_mg(a: static imut string) owns mut String{
	?catch(e){ return null }
	let b = mut nb()
	let s = mut ? new String(a)
	match Some(b){ match Some(b.emit){ match Some(s){
		let r = mut ? b.emit.mangleGlobalName(b.emit, s)
		return r
	} } }
	return null
}

func t_po(v: mut s64) owns mut String{
	?catch(e){ return null }
	let r = mut ? X86Emit.plusOffset(v)
	return r
}

func t_ot(v: mut s64) owns mut String{
	?catch(e){ return null }
	let r = mut ? X86Emit.offsetText(v)
	return r
}

func t_mt(v: mut s64) owns mut String{
	?catch(e){ return null }
	let b = mut nb()
	match Some(b){ match Some(b.regForm){
		let r = mut ? b.regForm.rfMemText(b.regForm, v)
		return r
	} }
	return null
}

func t_rt(a: static imut string) owns mut String{
	?catch(e){ return null }
	let b = mut nb()
	match Some(b){ match Some(b.regForm){
		let r = mut ? b.regForm.rfRegText(b.regForm, a)
		return r
	} }
	return null
}

func t_alias(r: static imut string, f: static imut string) mut bool{
	?catch(e){ return false }
	let a = mut ? new String(r)
	let b = mut ? new String(f)
	let res = mut false
	match Some(a){ match Some(b){ res = X86Core.regAliasOf(a, b) } }
	return res
}

func t_fl(x: static imut string) mut bool{
	?catch(e){ return false }
	let a = mut ? new String(x)
	let res = mut false
	match Some(a){ res = X86Core.isFloatLiteral(a) }
	return res
}

// prefixes and expected labels are comma separated; true when every label matches in order
func t_labels(prefixes: static imut string, want: static imut string) mut bool{
	?catch(e){ return false }
	let b = mut nb()
	let all = mut ? new String()
	let src = mut ? new String(prefixes)
	let cur = mut ? new String()
	match Some(src){
		let n = mut src.length(src)
		for i in 0..n{
			let c = mut src.charAt(src, i)
			if c == ','{
				match Some(b){ match Some(b.regForm){ match Some(cur){
					let l = mut ? b.regForm.newInternalLabel(b.regForm, cur)
					match Some(all){
						? all.append(all, l)
						? all.append(all, ",")
					}
				} } }
				cur = ? new String()
			} else{
				match Some(cur){ ? cur.appendChar(cur, c) }
			}
		}
	}
	let ok = mut false
	match Some(all){ ok = all.equals(all, want) }
	return ok
}

func state_ok(b: ref imut X86Backend, mask: mut s32, used: imut bool) mut bool{
	let r = mut false
	match Some(b){
		r = b.core.rfVarMask == mask && b.core.rfVarUsed == used
	}
	return r
}

func c_reg(name: static imut string, tok: static imut string, want: static imut string, mask: mut s32, used: imut bool) void{
	?catch(e){ check(name, false)
		return }
	let b = mut nb()
	let s = mut ? new String(tok)
	match Some(b){ match Some(b.regForm){ match Some(s){
		let g = try b.regForm.rfReg(b.regForm, s) catch(err){
			check(name, String.literalsEqual(want, "EX") && state_ok(b, mask, used))
			return
		}
		check(name, String.literalsEqual(g, want) && state_ok(b, mask, used))
		return
	} } }
	check(name, false)
}

func t_mem(ov: static imut string, hasOv: imut bool, ix: static imut string, hasIx: imut bool, scale: mut s64, disp: mut s64, base: static imut string) owns mut String{
	?catch(e){ return null }
	let b = mut nb()
	if hasOv{
		let t = mut ? String.from(ov)
		match Some(b){ b.core.rfMemOverride = t }
	}
	if hasIx{
		let t = mut ? String.from(ix)
		match Some(b){ b.core.rfIdxReg = t }
	}
	match Some(b){
		b.core.rfIdxScale = scale
		b.core.rfIdxDisp = disp
	}
	match Some(b){ match Some(b.gen){
		let r = mut ? b.gen.rfMemOperand(b.gen, base)
		return r
	} }
	return null
}

func c_x(name: static imut string, a: static imut string, want: static imut string) void{ let r = mut t_x(a)
	chk(name, r, want) }
func c_ml(name: static imut string, a: static imut string, want: static imut string) void{ let r = mut t_ml(a)
	chk(name, r, want) }
func c_mg(name: static imut string, a: static imut string, want: static imut string) void{ let r = mut t_mg(a)
	chk(name, r, want) }
func c_po(name: static imut string, v: mut s64, want: static imut string) void{ let r = mut t_po(v)
	chk(name, r, want) }
func c_ot(name: static imut string, v: mut s64, want: static imut string) void{ let r = mut t_ot(v)
	chk(name, r, want) }
func c_mt(name: static imut string, v: mut s64, want: static imut string) void{ let r = mut t_mt(v)
	chk(name, r, want) }
func c_rt(name: static imut string, a: static imut string, want: static imut string) void{ let r = mut t_rt(a)
	chk(name, r, want) }
func c_mem(name: static imut string, ov: static imut string, hasOv: imut bool, ix: static imut string, hasIx: imut bool, scale: mut s64, disp: mut s64, base: static imut string, want: static imut string) void{
	let r = mut t_mem(ov, hasOv, ix, hasIx, scale, disp, base)
	chk(name, r, want)
}
'''
HEAD += '''
func t_min() mut s64{
	let:<mut s64> m = mut -9223372036854775807
	let:<mut s64> one = mut 1
	return m - one
}
'''
print(HEAD)
parts = [lines[i:i + 100] for i in range(0, len(lines), 100)]
for k, ps in enumerate(parts):
    print("func part%d() void{" % k)
    print("\n".join(ps))
    print("}\n")
print("func main() void{")
for k in range(len(parts)):
    print("\tpart%d()" % k)
print("}")
