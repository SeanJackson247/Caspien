#!/usr/bin/env python3
"""usage: gen_codegen_marks_test.py lines.txt > tests/codegen_marks_test.caspien (lines: check calls printed by a Java harness over X86Generator.varMarksNeeded/expandVarMarks and X86Emit.emitHeader/comment)."""
import sys, re
rows = [l.rstrip("\n") for l in open(sys.argv[1]).read().split("\n") if l.strip()]
HEAD = '''// Differential test of the converted register-save mark helpers (varMarksNeeded, expandVarMarks) and emitHeader/comment against the Java originals (check lines generated by gen_codegen_marks_test.py).
import "stdlib/libc.caspien"
import "stdlib/gt/*"
import "../Codegen/src/main/java/caspien/codegen/codegenCaspien/x86backend/X86Backend.caspien"

func check(name: static imut string, ok: imut bool) void{
	unsafe extern{
		if ok{ printf("PASS %s\\n", name) }
		else{ printf("FAIL %s\\n", name) }
	}
}

func nb(win: imut bool) owns mut X86Backend{
	?catch(e){ return null }
	if win{
		let w = mut ? new X86Backend(CodegenTarget.WINDOWS_GNU_X64)
		? w.wire(w)
		return w
	}
	let b = mut ? new X86Backend(CodegenTarget.LINUX_X64)
	? b.wire(b)
	return b
}

func chk(name: static imut string, got: ref imut String, want: static imut string) void{
	let ok = mut String.literalsEqual(want, "EX")
	match Some(got){
		ok = got.equals(got, want)
	}
	check(name, ok)
}

func c_vmn(name: static imut string, text: static imut string, start: mut s32, want: mut s32) void{
	?catch(e){
		check(name, false)
		return
	}
	let b = mut nb(false)
	let t = mut ? new String(text)
	let:<mut s32> r = mut -1
	match Some(b){ match Some(b.core){ b.core.out = t } }
	match Some(b){ match Some(b.gen){ r = ? b.gen.varMarksNeeded(b.gen, start) } }
	check(name, r == want)
}

func c_evm(name: static imut string, text: static imut string, s0: static imut string, s1: static imut string, s2: static imut string, start: mut s32, want: static imut string) void{
	?catch(e){
		check(name, String.literalsEqual(want, "EX"))
		return
	}
	let b = mut nb(false)
	let t = mut ? new String(text)
	let a0 = mut ? new String(s0)
	let a1 = mut ? new String(s1)
	let a2 = mut ? new String(s2)
	match Some(b){ match Some(b.core){ b.core.out = t } }
	match Some(b){ match Some(b.core){ b.core.vSlots.setAt(b.core.vSlots, 0, a0) } }
	match Some(b){ match Some(b.core){ b.core.vSlots.setAt(b.core.vSlots, 1, a1) } }
	match Some(b){ match Some(b.core){ b.core.vSlots.setAt(b.core.vSlots, 2, a2) } }
	match Some(b){ match Some(b.gen){ ? b.gen.expandVarMarks(b.gen, start) } }
	let got = mut ? new String()
	match Some(b){ match Some(b.core){ got = ? b.core.out.substring(b.core.out, 0) } }
	chk(name, got, want)
}

func c_hdr(name: static imut string, win: imut bool, want: static imut string) void{
	?catch(e){
		check(name, false)
		return
	}
	let b = mut nb(win)
	let c1 = mut ? new String("hello \\"world\\"  r13")
	let c2 = mut ? new String()
	match Some(b){ match Some(b.emit){ ? b.emit.emitHeader(b.emit) } }
	match Some(b){ match Some(b.emit){ b.emit.emitFooter(b.emit) } }
	match Some(b){ match Some(b.emit){ ? b.emit.comment(b.emit, c1) } }
	match Some(b){ match Some(b.emit){ ? b.emit.comment(b.emit, c2) } }
	let got = mut ? new String()
	match Some(b){ match Some(b.core){ got = ? b.core.out.substring(b.core.out, 0) } }
	chk(name, got, want)
}
'''
print(HEAD)
parts = [rows[i:i + 100] for i in range(0, len(rows), 100)]
for k, ps in enumerate(parts):
    print("func part%d() void{" % k)
    print("\n".join(ps))
    print("}\n")
print("func main() void{")
for k in range(len(parts)):
    print("\tpart%d()" % k)
print("}")
