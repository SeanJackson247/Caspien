#!/usr/bin/env python3
"""usage: gen_codegen_regnames_test.py lines.txt > tests/codegen_regnames_test.caspien (lines: c_gen calls printed by a Java harness over the register-name and float-pool helpers)."""
import sys, re
rows = [l.rstrip("\n") for l in open(sys.argv[1]).read().split("\n") if l.strip()]
HEAD = '''// Differential test of the converted register-save mark helpers (varMarksNeeded, expandVarMarks) and emitHeader/comment against the Java originals (check lines generated by gen_codegen_marks_test.py).
import "../stdlib/libc.caspien"
import "../stdlib/gt/*"
import "../Codegen/src/main/java/caspien/codegen/codegenCaspien/x86backend/X86Backend.caspien"

func check(name: static imut string, ok: imut bool) void{
	unsafe extern{
		if ok{ printf("PASS %s\\n", name) }
		else{ printf("FAIL %s\\n", name) }
	}
}

func nb(win: imut bool) owns mut X86Backend{
	?catch(e){ return null }
	if win{
		let w = mut ? new X86Backend(CodegenTarget.WINDOWS_GNU_X64)
		? w.wire(w)
		return w
	}
	let b = mut ? new X86Backend(CodegenTarget.LINUX_X64)
	? b.wire(b)
	return b
}

func chk(name: static imut string, got: ref imut String, want: static imut string) void{
	let ok = mut String.literalsEqual(want, "EX")
	match Some(got){
		ok = got.equals(got, want)
	}
	check(name, ok)
}

func parseSpec(spec: static imut string, b: ref mut X86Backend, mem: imut bool) owns mut String{
	?catch(e){ return null }
	let out = mut ? new String()
	let s = mut ? new String(spec)
	let n = mut s.length(s)
	let tok = mut ? new String()
	let bitsText = mut ? new String()
	for i in 0..n{
		let c = mut s.charAt(s, i)
		if c == ':'{
			bitsText = ? tok.substring(tok, 0)
			tok = ? new String()
		} else if c == ';'{
			let bits = mut ? bitsText.parseS64(bitsText)
			let w = mut ? tok.parseS64(tok)
			let part = mut ? new String()
			if mem{
				match Some(b){ match Some(b.gen){ part = ? b.gen.floatPoolMem(b.gen, bits, wrap:<s32>(w)) } }
			}
			if mem == false{
				match Some(b){ match Some(b.gen){ part = ? b.gen.floatPoolLabel(b.gen, bits, wrap:<s32>(w)) } }
			}
			? out.append(out, part)
			? out.append(out, "|")
			tok = ? new String()
		} else{
			? tok.appendChar(tok, c)
		}
	}
	return out
}

func t_gen(win: imut bool, op: static imut string, a1: static imut string, a2: static imut string, num: mut s64, sz: mut s32) owns mut String{
	?catch(e){ return null }
	let b = mut nb(win)
	let s1 = mut ? new String(a1)
	let s2 = mut ? new String(a2)
	let n32 = mut wrap:<s32>(num)
	let out = mut ? new String()
	if String.literalsEqual(op, "argReg"){
		match Some(b){ match Some(b.calls){ let r1 = b.calls.argReg(b.calls, n32)
			out = ? String.from(r1) } }
	} else if String.literalsEqual(op, "argFloatReg"){
		match Some(b){ match Some(b.calls){ let r2 = b.calls.argFloatReg(b.calls, n32)
			out = ? String.from(r2) } }
	} else if String.literalsEqual(op, "rfArgReg"){
		match Some(b){ match Some(b.gen){ let r3 = ? b.gen.rfArgReg(b.gen, n32)
			out = ? String.from(r3) } }
	} else if String.literalsEqual(op, "bsar"){
		match Some(b){ match Some(b.calls){ out = ? b.calls.buildStackArgReservation(b.calls, num) } }
	} else if String.literalsEqual(op, "rfXmmA"){
		match Some(b){ match Some(b.gen){ let r4 = b.gen.rfXmmA(b.gen)
			out = ? String.from(r4) } }
	} else if String.literalsEqual(op, "rfXmmB"){
		match Some(b){ match Some(b.gen){ let r5 = b.gen.rfXmmB(b.gen)
			out = ? String.from(r5) } }
	} else if String.literalsEqual(op, "yPhys"){
		match Some(b){ match Some(b.gen){ let r6 = ? b.gen.yPhys(b.gen, n32)
			out = ? String.from(r6) } }
	} else if String.literalsEqual(op, "xvPhys"){
		match Some(b){ match Some(b.gen){ let r7 = ? b.gen.xvPhys(b.gen, n32)
			out = ? String.from(r7) } }
	} else if String.literalsEqual(op, "xvReg"){
		match Some(b){ match Some(b.gen){ let r8 = ? b.gen.xvReg(b.gen, s1)
			out = ? String.from(r8) } }
	} else if String.literalsEqual(op, "rfDispMem"){
		match Some(b){ match Some(b.gen){ out = ? b.gen.rfDispMem(b.gen, s1, num) } }
	} else if String.literalsEqual(op, "rfFloatMem"){
		match Some(b){ match Some(b.gen){ out = ? b.gen.rfFloatMem(b.gen, s1, sz) } }
	} else if String.literalsEqual(op, "rfTimesTwoOperand"){
		let r = mut ? new String()
		let isNull = mut true
		match Some(b){ match Some(b.gen){
			let t = mut ? b.gen.rfTimesTwoOperand(b.gen, sz, s1, s2)
			match Some(t){
				isNull = false
				r = ? t.substring(t, 0)
			}
		} }
		if isNull{
			? out.append(out, "<null>")
		} else{
			out = r
		}
	} else if String.literalsEqual(op, "fpl"){
		let ps = mut parseSpec(a1, b, false)
		match Some(ps){ out = ? ps.substring(ps, 0) }
	} else if String.literalsEqual(op, "fpm"){
		let pm = mut parseSpec(a1, b, true)
		match Some(pm){ out = ? pm.substring(pm, 0) }
	}
	return out
}

func c_gen(name: static imut string, win: imut bool, op: static imut string, a1: static imut string, a2: static imut string, num: mut s64, sz: mut s32, want: static imut string) void{
	let r = mut t_gen(win, op, a1, a2, num, sz)
	chk(name, r, want)
}
'''
print(HEAD)
parts = [rows[i:i + 100] for i in range(0, len(rows), 100)]
for k, ps in enumerate(parts):
    print("func part%d() void{" % k)
    print("\n".join(ps))
    print("}\n")
print("func main() void{")
for k in range(len(parts)):
    print("\tpart%d()" % k)
print("}")
