#!/usr/bin/env python3
"""Generates sorting_naive/safe/unsafe.caspien (identical algorithm, only the element access differs):
   unsafe: unsafe dyn:<u64>, a[i];  safe: safe dyn:<u64>, every access under `match i in/into a`;
   naive: stdlib DynamicArray<u64>, a.get(a, i) / a.set(a, i, v) under `match i in/into a.backing`.
Arrays are 1-based (element 0 unused) so that Hoare's `j = lo - 1` never underflows an unsigned index."""
import sys, os

class Gen:
    def __init__(self, mode):
        self.mode = mode; self.out = []; self.ind = 2; self.uid = 0
    def L(self, s): self.out.append("\t" * self.ind + s)
    def open(self, s): self.L(s); self.ind += 1
    def close(self): self.ind -= 1; self.L("}")
    def els(self): self.ind -= 1; self.L("}"); self.L("else{"); self.ind += 1
    def let(self, n, e): self.L(f"let {n} = mut ({e})" if any(c in e for c in " +-*/%") else f"let {n} = mut {e}")
    def brk(self, cond): self.open(f"if {cond}{{"); self.L("break"); self.close()
    def rd(self, arr, idx, dst):
        m = self.mode
        if m == "unsafe": self.L(f"{dst} = {arr}[{idx}]")
        elif m == "safe":
            self.open(f"match {idx} in {arr}{{"); self.L(f"{dst} = {arr}[{idx}]"); self.close()
        else:
            self.open(f"match {idx} in {arr}.backing{{"); self.L(f"{dst} = {arr}.get({arr}, {idx})"); self.close()
    def wr(self, arr, idx, val):
        m = self.mode
        if m == "unsafe": self.L(f"{arr}[{idx}] = {val}")
        elif m == "safe":
            self.open(f"match {idx} into {arr}{{"); self.L(f"{arr}[{idx}] = {val}"); self.close()
        else:
            self.open(f"match {idx} into {arr}.backing{{"); self.L(f"{arr}.set({arr}, {idx}, {val})"); self.close()
    def tmp(self, base):
        self.uid += 1; return f"{base}{self.uid}"
    def rdn(self, arr, idx, base="v"):          # declare + read
        n = self.tmp(base); self.L(f"let {n} = mut 0"); self.rd(arr, idx, n); return n
    def lcg(self):
        self.L("x = bits_and(x * 1664525 + 1013904223, 0xFFFFFFFF)")

    def siftdown(self, a, root, nn):
        self.open("loop{")
        c = self.tmp("c"); self.let(c, f"2 * {root}")
        self.brk(f"{c} > {nn}")
        c1 = self.tmp("c1"); self.let(c1, f"{c} + 1")
        self.open(f"if {c1} <= {nn}{{")
        x1 = self.rdn(a, c1); x0 = self.rdn(a, c)
        self.open(f"if {x1} > {x0}{{"); self.L(f"{c} = {c1}"); self.close()
        self.close()
        ar = self.rdn(a, root); ac = self.rdn(a, c)
        self.brk(f"{ar} >= {ac}")
        self.wr(a, root, ac); self.wr(a, c, ar)
        self.L(f"{root} = {c}")
        self.close()

    def merge_pass(self, src, dst, w):
        lo = self.tmp("lo"); self.L(f"let {lo} = mut 1")
        self.open("loop{")
        self.brk(f"{lo} > n")
        mid = self.tmp("mid"); hi = self.tmp("hi")
        self.let(mid, f"{lo} + {w}"); self.open(f"if {mid} > n1{{"); self.L(f"{mid} = n1"); self.close()
        self.let(hi, f"{lo} + 2 * {w}"); self.open(f"if {hi} > n1{{"); self.L(f"{hi} = n1"); self.close()
        i = self.tmp("i"); j = self.tmp("j"); k = self.tmp("k")
        self.L(f"let {i} = mut {lo}"); self.L(f"let {j} = mut {mid}"); self.L(f"let {k} = mut {lo}")
        self.open("loop{")
        self.brk(f"{i} >= {mid}"); self.brk(f"{j} >= {hi}")
        si = self.rdn(src, i); sj = self.rdn(src, j)
        self.open(f"if {si} <= {sj}{{"); self.wr(dst, k, si); self.L(f"{i} += 1"); self.close() if False else None
        self.els(); self.wr(dst, k, sj); self.L(f"{j} += 1"); self.close()
        self.L(f"{k} += 1")
        self.close()
        self.open("loop{"); self.brk(f"{i} >= {mid}"); v = self.rdn(src, i); self.wr(dst, k, v); self.L(f"{i} += 1"); self.L(f"{k} += 1"); self.close()
        self.open("loop{"); self.brk(f"{j} >= {hi}"); v = self.rdn(src, j); self.wr(dst, k, v); self.L(f"{j} += 1"); self.L(f"{k} += 1"); self.close()
        self.L(f"{lo} += 2 * {w}")
        self.close()

    def program(self):
        m = self.mode
        o = []
        title = {"unsafe": "UNSAFE variant: unsafe dynarrays of u64, no bounds proofs",
                 "safe": "SAFE variant: safe dynarrays of u64, every element access under a bounds proof (match i in/into a)",
                 "naive": "NAIVE variant: the stdlib DynamicArray<u64> class (get/set methods, each under its bounds proof)"}[m]
        o.append(f"// Sorting and searching benchmark (SORT_N values), {title}.")
        o.append("// Iterative quicksort (Hoare, middle pivot, explicit stack), bottom-up merge sort, heap sort, then n binary searches on the sorted array and")
        o.append("// 20 linear searches on the unsorted one. Arrays are 1-based (element 0 unused) so that Hoare's j = lo - 1 cannot underflow an unsigned index.")
        o.append("// Elements are u64 (the reference programs use 32-bit ints). Prints: hash binary-hits linear-hits OK|BAD. Generated by generate.py.")
        o.append('import "../../../stdlib/libc.caspien"')
        if m == "naive": o.append('import "../../../stdlib/dynamic_array.caspien"')
        for f in ("gt_init", "gt_register", "gt_alive_check", "gt_destruct"): o.append(f'import "../../../stdlib/{f}.caspien"')
        o.append("extern getenv(static imut string) static imut string")
        o.append("extern atol(static imut string) mut u64")
        o.append("")
        o.append("func main() void{")
        if m != "unsafe": o.append("\t?catch(e){ return }")
        o.append("\tunsafe{")
        self.out = o; self.ind = 2
        self.L("let n = mut 0"); self.L('n = atol(getenv("SORT_N"))')
        self.L("let n1 = mut (n + 1)"); self.L("let sz = mut (n + 1)")
        self.L("let:<mut u64> zero = mut 0")
        names = ["orig", "a", "b", "d", "tmp", "stk"]
        for nm in names:
            size = "256" if nm == "stk" else "sz"
            if m == "unsafe":
                self.L(f"let {nm} = mut unsafe dyn:<u64>([])"); self.L(f"{nm} = resize({nm}, {size})")
            elif m == "safe":
                self.L(f"let {nm} = mut ? dyn:<u64>([])"); self.L(f"{nm} = ? resize({nm}, {size}, zero)")
            else:
                self.L(f"let r_{nm} = mut ? dyn:<u64>([])"); self.L(f"r_{nm} = ? resize(r_{nm}, {size}, zero)")
                self.L(f"let {nm} = mut ? new DynamicArray:<u64>(r_{nm})")
        if m == "unsafe":
            for nm in names:
                self.open(f"for i in 0..{'256' if nm == 'stk' else 'sz'}{{"); self.L(f"{nm}[i] = 0"); self.close()
        self.L("let x = mut 12345")
        self.open("for i in 1..sz{")
        self.lcg(); self.L("let val = mut (x / 2)")
        for nm in ("orig", "a", "b", "d"): self.wr(nm, "i", "val")
        self.close()
        # ---- quicksort on a
        self.L("let sp = mut 0")
        self.L("let one = mut 1")
        self.wr("stk", "sp", "one"); self.L("sp += 1"); self.wr("stk", "sp", "n"); self.L("sp += 1")
        self.open("loop{")
        self.brk("sp == 0")
        self.L("sp -= 1"); self.L("let hi = mut 0"); self.rd("stk", "sp", "hi")
        self.L("sp -= 1"); self.L("let lo = mut 0"); self.rd("stk", "sp", "lo")
        self.open("loop{")
        self.brk("lo >= hi")
        self.L("let mm = mut ((lo + hi) / 2)"); self.L("let pivot = mut 0"); self.rd("a", "mm", "pivot")
        self.L("let i = mut lo"); self.L("let j = mut hi")
        self.open("loop{")
        self.brk("i > j")
        self.open("loop{"); ai = self.rdn("a", "i"); self.brk(f"{ai} >= pivot"); self.L("i += 1"); self.close()
        self.open("loop{"); aj = self.rdn("a", "j"); self.brk(f"{aj} <= pivot"); self.L("j -= 1"); self.close()
        self.open("if i <= j{")
        t1 = self.rdn("a", "i"); t2 = self.rdn("a", "j")
        self.wr("a", "i", t2); self.wr("a", "j", t1)
        self.L("i += 1"); self.L("j -= 1")
        self.close()
        self.close()
        self.L("let left = mut (j + i)"); self.L("let right = mut (hi + lo)")
        self.open("if left < right{")
        self.wr("stk", "sp", "i"); self.L("sp += 1"); self.wr("stk", "sp", "hi"); self.L("sp += 1"); self.L("hi = j")
        self.els()
        self.wr("stk", "sp", "lo"); self.L("sp += 1"); self.wr("stk", "sp", "j"); self.L("sp += 1"); self.L("lo = i")
        self.close()
        self.close()
        self.close()
        # ---- merge sort on b (tmp)
        self.L("let w = mut 1"); self.L("let dir = mut 0")
        self.open("loop{")
        self.brk("w >= n")
        self.open("if dir == 0{"); self.merge_pass("b", "tmp", "w"); self.L("dir = 1")
        self.els(); self.merge_pass("tmp", "b", "w"); self.L("dir = 0"); self.close()
        self.L("w *= 2")
        self.close()
        self.open("if dir == 1{")
        self.open("for i in 1..sz{"); v = self.rdn("tmp", "i"); self.wr("b", "i", v); self.close()
        self.close()
        # ---- heap sort on d
        self.L("let hr = mut (n / 2)")
        self.open("loop{")
        self.brk("hr == 0")
        self.L("let root = mut hr"); self.siftdown("d", "root", "n")
        self.L("hr -= 1")
        self.close()
        self.L("let e = mut n")
        self.open("loop{")
        self.brk("e < 2")
        d1 = self.rdn("d", "one"); de = self.rdn("d", "e")
        self.wr("d", "one", de); self.wr("d", "e", d1)
        self.L("let em = mut (e - 1)"); self.L("let root2 = mut 1"); self.siftdown("d", "root2", "em")
        self.L("e -= 1")
        self.close()
        # ---- verify + hash
        self.L("let h = mut 0"); self.L("let ok = mut 1"); self.L("let prev = mut 0")
        self.open("for i in 1..sz{")
        av = self.rdn("a", "i"); bv = self.rdn("b", "i"); dv = self.rdn("d", "i")
        self.L(f"h = bits_and(h * 31 + {av}, 0xFFFFFFFF)")
        self.open(f"if {av} != {bv}{{"); self.L("ok = 0"); self.close()
        self.open(f"if {av} != {dv}{{"); self.L("ok = 0"); self.close()
        self.open("if i > 1{"); self.open(f"if prev > {av}{{"); self.L("ok = 0"); self.close(); self.close()
        self.L(f"prev = {av}")
        self.close()
        # ---- binary searches
        self.L("let bs = mut 0")
        self.open("for k in 0..n{")
        self.lcg(); self.L("let key = mut (x / 2)")
        self.open("if k % 2 == 0{"); self.L("let kk = mut (key % n + 1)"); self.rd("orig", "kk", "key"); self.close()
        self.L("let lo2 = mut 1"); self.L("let hi2 = mut n1")
        self.open("loop{")
        self.brk("lo2 >= hi2")
        self.L("let m2 = mut ((lo2 + hi2) / 2)"); mv = self.rdn("a", "m2")
        self.open(f"if {mv} < key{{"); self.L("lo2 = m2 + 1"); self.els(); self.L("hi2 = m2"); self.close()
        self.close()
        self.open("if lo2 <= n{")
        fv = self.rdn("a", "lo2")
        self.open(f"if {fv} == key{{"); self.L("bs += 1"); self.close()
        self.close()
        self.close()
        # ---- linear searches
        self.L("let ls = mut 0")
        self.open("for k in 0..20{")
        self.lcg(); self.L("let key = mut (x / 2)")
        self.open("if k % 2 == 0{"); self.L("let kk = mut (key % n + 1)"); self.rd("orig", "kk", "key"); self.close()
        self.L("let li = mut 1")
        self.open("loop{")
        self.brk("li > n")
        lv = self.rdn("orig", "li")
        self.open(f"if {lv} == key{{"); self.L("ls += 1"); self.L("break"); self.close()
        self.L("li += 1")
        self.close()
        self.close()
        self.open("if ok == 1{"); self.L('printf("%llu %llu %llu OK\\n", h, bs, ls)'); self.els(); self.L('printf("%llu %llu %llu BAD\\n", h, bs, ls)'); self.close()
        o.append("\t}")
        o.append("}")
        return "\n".join(o) + "\n"

