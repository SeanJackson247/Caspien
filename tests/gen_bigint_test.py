#!/usr/bin/env python3
"""Generates tests/bigint_test.caspien. Expected values come from Python's integers (Java BigInteger semantics where they differ:
truncating divide/remainder, remainder with the dividend's sign, bitLength/bitCount of negatives, longValue wrap)."""
import random, sys, os

random.seed(20261015)
M32 = 0xFFFFFFFF

def trunc_div(a, b):
    q = abs(a) // abs(b)
    return q if (a < 0) == (b < 0) else -q

def trunc_rem(a, b):
    return a - trunc_div(a, b) * b

def java_bitlen(a):
    return (a if a >= 0 else ~a).bit_length()

def java_bitcount(a):
    return bin(a if a >= 0 else ~a).count("1")

def s64(a):
    a &= (1 << 64) - 1
    return a - (1 << 64) if a >= 1 << 63 else a

def radix_str(a, r):
    digs = "0123456789abcdefghijklmnopqrstuvwxyz"
    if a == 0:
        return "0"
    n, out = abs(a), []
    while n:
        out.append(digs[n % r])
        n //= r
    return ("-" if a < 0 else "") + "".join(reversed(out))

edge = [0, 1, -1, 2, -2, 9, 10, 255, 256, 65535, 65536, M32, M32 + 1, -M32, -(M32 + 1), (1 << 63) - 1, 1 << 63, -(1 << 63), -(1 << 63) - 1,
        (1 << 64) - 1, 1 << 64, -(1 << 64), (1 << 96) - 1, 1 << 96, 10**30, -10**30, 12345678901234567890123456789]

def rnd(bits):
    v = random.getrandbits(bits) | (1 << (bits - 1))
    return -v if random.random() < 0.5 else v

rand = [rnd(b) for b in (7, 20, 31, 32, 33, 40, 63, 64, 65, 90, 96, 128, 129, 200, 333)]
vals = edge + rand

def pairs(count):
    ps = [(a, b) for a in edge[:14] for b in edge[:14]]
    for _ in range(count):
        ps.append((random.choice(vals), random.choice(vals)))
    return ps

def divpairs(count):
    ps = []
    for _ in range(count):
        topc = random.choice([0x80000000, M32, random.getrandbits(32) | 0x80000000, random.getrandbits(31) + 1])
        nl = random.choice([2, 2, 3, 4, 5])
        v = topc
        for _i in range(nl - 1):
            v = (v << 32) | random.choice([0, M32, random.getrandbits(32)])
        q = random.getrandbits(random.choice([1, 32, 33, 64, 100, 160]))
        r = random.choice([v - 1, random.randrange(v), 0, 1])
        u = q * v + r
        sa = random.choice([1, -1]); sb = random.choice([1, -1])
        ps.append((sa * u, sb * v))
    return ps

def lit(a):
    if isinstance(a, str):
        return '"%s"' % a
    return '"%d"' % a

# usage: gen_bigint_test.py            -> tests/bigint_test.caspien (8 cases per category: small enough for the aggressive inliner)
#        gen_bigint_test.py full PATH  -> the exhaustive program (about 7000 cases) at PATH, run by bigint_check.sh
FULL = len(sys.argv) > 2 and sys.argv[1] == "full"
SMALL = not FULL
out = []
w = out.append
w("// GENERATED by gen_bigint_test.py%s (expected" % ("" if SMALL else " full") + " values come from Python integer arithmetic, Java BigInteger semantics). stdlib/bigint.caspien.")
w('import "../stdlib/libc.caspien"')
w('import "../stdlib/bigint.caspien"')
w('import "../stdlib/gt/*"')
w('''
func report(name: static imut string, bad: imut u64, total: imut u64) void{
	unsafe extern{
		if bad == 0{ printf("PASS %s (%d cases)\\n", name, total) }
		else{ printf("FAIL %s: %d of %d wrong\\n", name, bad, total) }
	}
}

func sameText(s: ref some imut String, expected: static imut string) mut bool{
	?catch(ce){ return mut false }
	let ex = mut ? dyn(expected)
	let n = mut len(s.chars.backing)
	if n != len(ex){ return mut false }
	for i in 0..n{
		match i in s.chars.backing{
			match i in ex{
				if s.chars.backing[i] != ex[i]{ return mut false }
			}
		}
	}
	return mut true
}

@throws
func binop(op: mut u64, sa: static imut string, sb: static imut string) owns some mut BigInt{
	?catch(ce){ throw ce }
	let a = mut ? BigInt.parse(sa, 10)
	let b = mut ? BigInt.parse(sb, 10)
	if op == 0{ let r = mut ? a.add(a, b); return r }
	if op == 1{ let r = mut ? a.subtract(a, b); return r }
	if op == 2{ let r = mut ? a.multiply(a, b); return r }
	if op == 3{ let r = mut ? a.divide(a, b); return r }
	if op == 4{ let r = mut ? a.remainder(a, b); return r }
	if op == 5{ let r = mut ? a.mod(a, b); return r }
	if op == 6{ let r = mut ? a.bitAnd(a, b); return r }
	if op == 7{ let r = mut ? a.bitOr(a, b); return r }
	if op == 8{ let r = mut ? a.xor(a, b); return r }
	if op == 9{ let r = mut ? a.andNot(a, b); return r }
	if op == 10{ let r = mut ? a.min(a, b); return r }
	if op == 11{ let r = mut ? a.max(a, b); return r }
	if op == 12{ let r = mut ? BigInt.valueOf(a.compareTo(a, b)); return r }
	let z = mut 0
	if a.equals(a, b){ z = 1 }
	let r2 = mut ? BigInt.valueOf(wrap:<s64>(z))
	return r2
}

@throws
func unop(op: mut u64, sa: static imut string, arg: mut u64) owns some mut String{
	?catch(ce){ throw ce }
	let a = mut ? BigInt.parse(sa, 10)
	if op == 20{ let r = mut ? a.negate(a); let s = mut ? r.toString(r); return s }
	if op == 21{ let r = mut ? a.abs(a); let s = mut ? r.toString(r); return s }
	if op == 22{ let r = mut ? a.bitNot(a); let s = mut ? r.toString(r); return s }
	if op == 23{ let r = mut ? a.shiftLeft(a, arg); let s = mut ? r.toString(r); return s }
	if op == 24{ let r = mut ? a.shiftRight(a, arg); let s = mut ? r.toString(r); return s }
	if op == 25{ let r = mut ? a.pow(a, arg); let s = mut ? r.toString(r); return s }
	if op == 26{ let s = mut ? a.toStringRadix(a, arg); return s }
	if op == 27{ let v = mut a.bitLength(a); let r = mut ? BigInt.fromU64(v); let s = mut ? r.toString(r); return s }
	if op == 28{ let v = mut a.bitCount(a); let r = mut ? BigInt.fromU64(v); let s = mut ? r.toString(r); return s }
	if op == 29{
		let v = mut 0
		if a.testBit(a, arg){ v = 1 }
		let r = mut ? BigInt.fromU64(v); let s = mut ? r.toString(r); return s
	}
	if op == 30{ let v = mut a.toS64(a); let r = mut ? BigInt.valueOf(v); let s = mut ? r.toString(r); return s }
	if op == 31{
		let v = mut 0
		if a.fitsS64(a){ v = 1 }
		let r = mut ? BigInt.fromU64(v); let s = mut ? r.toString(r); return s
	}
	if op == 32{
		let v = mut 0
		if a.fitsU64(a){ v = 1 }
		let r = mut ? BigInt.fromU64(v); let s = mut ? r.toString(r); return s
	}
	if op == 33{ let v = mut a.signum(a); let r = mut ? BigInt.valueOf(v); let s = mut ? r.toString(r); return s }
	let r2 = mut ? a.toString(a)
	return r2
}

func okBin(op: mut u64, sa: static imut string, sb: static imut string, expected: static imut string) mut bool{
	?catch(ce){ return mut false }
	let r = mut ? binop(op, sa, sb)
	let s = mut ? r.toString(r)
	return sameText(s, expected)
}

func okUn(op: mut u64, sa: static imut string, arg: mut u64, expected: static imut string) mut bool{
	?catch(ce){ return mut false }
	let s = mut ? unop(op, sa, arg)
	return sameText(s, expected)
}

func okParse(text: static imut string, radix: mut u64, expected: static imut string) mut bool{
	?catch(ce){ return mut false }
	let r = mut ? BigInt.parse(text, radix)
	let s = mut ? r.toString(r)
	return sameText(s, expected)
}

func okFromS64(v: mut s64, expected: static imut string) mut bool{
	?catch(ce){ return mut false }
	let r = mut ? BigInt.valueOf(v)
	let s = mut ? r.toString(r)
	return sameText(s, expected)
}

func okFromU64(v: mut u64, expected: static imut string) mut bool{
	?catch(ce){ return mut false }
	let r = mut ? BigInt.fromU64(v)
	let s = mut ? r.toString(r)
	return sameText(s, expected)
}

func threwBin(op: mut u64, sa: static imut string, sb: static imut string) mut bool{
	?catch(ce){ return mut true }
	let r = mut ? binop(op, sa, sb)
	return mut false
}

func threwParse(text: static imut string, radix: mut u64) mut bool{
	?catch(ce){ return mut true }
	let r = mut ? BigInt.parse(text, radix)
	return mut false
}

func main() void{
	let bad = mut 0''')

def cat(name, lines):
    if SMALL and len(lines) > 8:
        step = len(lines) // 8
        lines = lines[::step][:8]
    w("\tbad = 0")
    for l in lines:
        w("\tif %s == false{ bad = bad + 1 }" % l)
    w('\treport("%s", bad, %d)' % (name, len(lines)))

def binlines(op, f, ps):
    L = []
    for a, b in ps:
        r = f(a, b)
        if r is None:
            continue
        L.append('okBin(%d, %s, %s, %s)' % (op, lit(a), lit(b), lit(r)))
    return L

P = pairs(120)
cat("add", binlines(0, lambda a, b: a + b, P))
cat("subtract", binlines(1, lambda a, b: a - b, P))
cat("multiply", binlines(2, lambda a, b: a * b, P))
DP = [(a, b) for a, b in P if b != 0] + divpairs(150)
cat("divide", binlines(3, trunc_div, DP))
cat("remainder", binlines(4, trunc_rem, DP))
cat("mod", binlines(5, lambda a, b: a % b if b > 0 else None, DP))
cat("and", binlines(6, lambda a, b: a & b, P))
cat("or", binlines(7, lambda a, b: a | b, P))
cat("xor", binlines(8, lambda a, b: a ^ b, P))
cat("andNot", binlines(9, lambda a, b: a & ~b, P))
cat("min", binlines(10, min, P))
cat("max", binlines(11, max, P))
cat("compareTo", binlines(12, lambda a, b: (a > b) - (a < b), P))
cat("equals", binlines(13, lambda a, b: int(a == b), P))

def unlines(op, f, argset):
    L = []
    for a in vals:
        for n in argset:
            L.append('okUn(%d, %s, %d, %s)' % (op, lit(a), n, lit(f(a, n))))
            if len(argset) > 1 and random.random() < 0.0:
                pass
    return L

cat("negate", unlines(20, lambda a, n: -a, [0]))
cat("abs", unlines(21, lambda a, n: abs(a), [0]))
cat("not", unlines(22, lambda a, n: ~a, [0]))
cat("shiftLeft", unlines(23, lambda a, n: a << n, [0, 1, 31, 32, 33, 64, 100]))
cat("shiftRight", unlines(24, lambda a, n: a >> n, [0, 1, 31, 32, 33, 64, 100, 400]))
cat("pow", unlines(25, lambda a, n: a ** n, [0, 1, 2, 3, 7]))
for r in (2, 8, 10, 16, 36):
    cat("toStringRadix %d" % r, unlines(26, lambda a, n: radix_str(a, n), [r]))
cat("bitLength", unlines(27, lambda a, n: java_bitlen(a), [0]))
cat("bitCount", unlines(28, lambda a, n: java_bitcount(a), [0]))
cat("testBit", unlines(29, lambda a, n: (a >> n) & 1, [0, 1, 31, 32, 63, 64, 70, 130, 500]))
cat("toS64 (longValue)", unlines(30, lambda a, n: s64(a), [0]))
cat("fitsS64", unlines(31, lambda a, n: int(-(1 << 63) <= a < (1 << 63)), [0]))
cat("fitsU64", unlines(32, lambda a, n: int(0 <= a < (1 << 64)), [0]))
cat("signum", unlines(33, lambda a, n: (a > 0) - (a < 0), [0]))

# parse in several radixes (upper and lower case, explicit plus sign)
PL = []
for a in vals:
    for r in (2, 7, 10, 16, 36):
        t = radix_str(a, r)
        if random.random() < 0.3:
            t = t.upper()
        if a >= 0 and random.random() < 0.2:
            t = "+" + t
        PL.append('okParse("%s", %d, %s)' % (t, r, lit(a)))
cat("parse", PL)
cat("valueOf", ['okFromS64(%d, %s)' % (v, lit(v)) for v in (0, 1, -1, 5, -5, 2**31, -2**31, 2**32, -2**32, 2**63 - 1, -2**63)])
cat("fromU64", ['okFromU64(%d, %s)' % (v, lit(v)) for v in (0, 1, 2**32 - 1, 2**32, 2**63, 2**64 - 1)])

w("\tbad = 0")
errs = [
    'threwBin(3, "5", "0") == false',
    'threwBin(4, "5", "0") == false',
    'threwBin(3, "0", "0") == false',
    'threwBin(5, "5", "0") == false',
    'threwBin(5, "5", "-3") == false',
    'threwBin(0, "5", "6") == true',
    'threwBin(3, "5", "6") == true',
    'threwParse("", 10) == false',
    'threwParse("-", 10) == false',
    'threwParse("12x4", 10) == false',
    'threwParse("99x", 10) == false',
    'threwParse("19", 8) == false',
    'threwParse("1", 1) == false',
    'threwParse("1", 37) == false',
    'threwParse("12345678901234567890", 10) == true',
]
for e in errs:
    w("\tif %s{ bad = bad + 1 }" % e)
w('\treport("errors", bad, %d)' % len(errs))
w("}")
open(sys.argv[2] if FULL else os.path.join(os.path.dirname(os.path.abspath(__file__)), "bigint_test.caspien"), "w").write("\n".join(out) + "\n")
print("cases written")
